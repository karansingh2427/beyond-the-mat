export const primarySeries: Posture[] = primarySeriesRaw.map((p) => ({
  ...p,
  series: "primary" as const,
}));

export const intermediateSeries: Posture[] = intermediateSeriesRaw.map((p) => ({
  ...p,
  series: "intermediate" as const,
}));

export const allPostures: Posture[] = [...primarySeries, ...intermediateSeries];

export const seriesSections: SeriesSection[] = [
  "Sūryanamaskāra",
  "Standing",
  "Seated",
  "Backbends",
  "Twists & binds",
  "Arm balances",
  "Finishing",
];

export function getSeriesMeta(id: SeriesId) {
  return seriesMeta.find((s) => s.id === id)!;
}

export function getPosturesForSeries(id: SeriesId) {
  return id === "primary" ? primarySeries : intermediateSeries;
}

export function getPosture(slug: string) {
  return allPostures.find((p) => p.slug === slug);
}

export function posturesBySection(seriesId: SeriesId = "primary") {
  const list = getPosturesForSeries(seriesId);
  return seriesSections
    .map((section) => ({
      section,
      postures: list.filter((p) => p.section === section),
    }))
    .filter((g) => g.postures.length > 0);
}
